// ─────────────────────────────────────────────────────────────────────────────
// matchContext — "למה המשתמש הגיע לפרופיל הזה", כדי שמסך הפרופיל יציג את הציון הנכון
// בלי לנחש איזה אלגוריתם רלוונטי. עובר כפרמטר ניווט (JSON) מכל נקודת כניסה, ונגזר
// בצ'אט מתוך מקור ההתאמה (tripID). האלגוריתמים עצמם לא משתנים — רק ההקשר עובר.
//
// צורה: { type, tripId?, score? }
//   type   — "general" (שאלון היכרות) | "trip" (העדפות טיול) | "discovery" (גילוי, ללא יחס התאמה)
//   tripId — קיים כש-type === "trip"; מזהה הטיול שההתאמה נקשרה אליו
//   score  — הציון שכבר חושב במסך המקור (matchesForYou/TripMatches). כשחסר (כניסה מצ'אט),
//            הפרופיל מחשב אותו בעצמו עם אותה פונקציית ניקוד + נתוני ההקשר.
// ─────────────────────────────────────────────────────────────────────────────

export const MATCH_CONTEXT = {
  GENERAL: "general",
  TRIP: "trip",
  DISCOVERY: "discovery",
};

// תווית הצגה לציון לפי סוג ההקשר. גילוי (discovery) אינו יחס התאמה — אין לו ציון.
export function matchContextLabel(type) {
  return type === MATCH_CONTEXT.TRIP ? "התאמה לטיול" : "התאמה";
}
